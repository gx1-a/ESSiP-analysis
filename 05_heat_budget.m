function edges = centres_to_edges(c)
    c = double(c(:));

    if numel(c)<2
        error('At least two grid-cell centers are required to construct edges.');
    end

    middle = 0.5*(c(1:end-1)+c(2:end));

    edges = [ ...
        c(1)-(middle(1)-c(1)); ...
        middle; ...
        c(end)+(c(end)-middle(end))];
end

function dt = ensure_utc_datetime(raw)
    if isdatetime(raw)
        dt = raw;

        if isempty(dt.TimeZone)
            dt.TimeZone = 'UTC';
        else
            dt.TimeZone = 'UTC';
        end
        return;
    end

    raw = string(raw);
    dt = NaT(numel(raw),1,'TimeZone','UTC');

    formats = { ...
        'yyyy-MM-dd HH:mm:ss.S', ...
        'yyyy-MM-dd HH:mm:ss', ...
        'yyyy-MM-dd''T''HH:mm:ss.S', ...
        'yyyy-MM-dd''T''HH:mm:ss', ...
        'yyyyMMdd''T''HHmmss'};

    for i = 1:numel(raw)
        ok = false;

        for f = 1:numel(formats)
            try
                dt(i) = datetime( ...
                    raw(i), ...
                    'InputFormat',formats{f}, ...
                    'TimeZone','UTC');
                ok = true;
                break;
            catch
            end
        end

        if ~ok
            dt(i) = parse_sentinel1_midtime(raw(i));
        end
    end
end

function mid_time = parse_sentinel1_midtime(name_or_path)
    [~,name,~] = fileparts(char(name_or_path));

    tokens = regexp(name, ...
        '(\d{8}T\d{6})_(\d{8}T\d{6})', ...
        'tokens','once');

    if isempty(tokens)
        error('Could not parse Sentinel-1 acquisition time from name: %s',name);
    end

    t1 = datetime(tokens{1}, ...
        'InputFormat','yyyyMMdd''T''HHmmss', ...
        'TimeZone','UTC');

    t2 = datetime(tokens{2}, ...
        'InputFormat','yyyyMMdd''T''HHmmss', ...
        'TimeZone','UTC');

    mid_time = t1+(t2-t1)/2;
end

function token = extract_date_token(text_value)
    token_char = regexp( ...
        char(text_value), ...
        '\d{8}','match','once');

    if isempty(token_char)
        token = "";
    else
        token = string(token_char);
    end
end

function catalog = build_mask_catalog( ...
    result_dir,manual_mask_dir,require_manual_masks)

    result_files = dir(fullfile(result_dir,'Result4_*.mat'));
    final_files = dir(fullfile(manual_mask_dir,'FinalMask_*.mat'));

    result_tokens = strings(numel(result_files),1);
    for i = 1:numel(result_files)
        result_tokens(i) = extract_date_token(result_files(i).name);
    end
    result_tokens = unique(result_tokens(strlength(result_tokens)==8));

    DateToken = strings(numel(final_files),1);
    MaskFile = strings(numel(final_files),1);

    for i = 1:numel(final_files)
        DateToken(i) = extract_date_token(final_files(i).name);
        MaskFile(i) = string(fullfile( ...
            final_files(i).folder,final_files(i).name));
    end

    valid = strlength(DateToken)==8;
    DateToken = DateToken(valid);
    MaskFile = MaskFile(valid);

    if isempty(DateToken)
        error('No expert-confirmed FinalMask files were found in %s', ...
            manual_mask_dir);
    end

    [DateToken,order] = sort(DateToken);
    MaskFile = MaskFile(order);
    [DateToken,ia] = unique(DateToken,'stable');
    MaskFile = MaskFile(ia);

    if require_manual_masks && ~isempty(result_tokens)
        missing = setdiff(result_tokens,DateToken);
        extra = setdiff(DateToken,result_tokens);

        if ~isempty(missing)
            error(['Expert QC is incomplete. Missing FinalMask dates: %s. ' ...
                'Automatic RF fallback is disabled.'], ...
                strjoin(cellstr(missing),', '));
        end

        if ~isempty(extra)
            warning('FinalMask dates without matching Result4 files: %s', ...
                strjoin(cellstr(extra),', '));
        end
    end

    for i = 1:numel(MaskFile)
        names = string({whos('-file',char(MaskFile(i))).name});
        if ~ismember("final_mask",names)
            error('Expert mask file lacks final_mask: %s',char(MaskFile(i)));
        end
        if require_manual_masks && ~ismember("qc_status",names)
            error('Expert mask file lacks qc_status metadata: %s',char(MaskFile(i)));
        end
    end

    Priority = 2*ones(numel(DateToken),1);
    catalog = table(DateToken,MaskFile,Priority);
end

function [mask,source,threshold, ...
    result_source_name,result_mid_utc,grid_xv,grid_yv] = ...
