    end

    u = read_era5_cells( ...
        inst_file,'u10', ...
        lon_raw_idx,lat_raw_idx, ...
        lon_perm,lat_perm);

    v = read_era5_cells( ...
        inst_file,'v10', ...
        lon_raw_idx,lat_raw_idx, ...
        lon_perm,lat_perm);

    Ta = read_era5_cells( ...
        inst_file,'t2m', ...
        lon_raw_idx,lat_raw_idx, ...
        lon_perm,lat_perm);

    Td = read_era5_cells( ...
        inst_file,'d2m', ...
        lon_raw_idx,lat_raw_idx, ...
        lon_perm,lat_perm);

    p = read_era5_cells( ...
        inst_file,'sp', ...
        lon_raw_idx,lat_raw_idx, ...
        lon_perm,lat_perm);

    msl = read_era5_cells( ...
        inst_file,'msl', ...
        lon_raw_idx,lat_raw_idx, ...
        lon_perm,lat_perm);

    sic = read_era5_cells( ...
        inst_file,'siconc', ...
        lon_raw_idx,lat_raw_idx, ...
        lon_perm,lat_perm);

    LWd = read_era5_cells( ...
        avg_file,'avg_sdlwrf', ...
        lon_raw_idx,lat_raw_idx, ...
        lon_perm,lat_perm);

    SWd = read_era5_cells( ...
        avg_file,'avg_sdswrf', ...
        lon_raw_idx,lat_raw_idx, ...
        lon_perm,lat_perm);

    SH_era5 = read_era5_cells( ...
        avg_file,'avg_ishf', ...
        lon_raw_idx,lat_raw_idx, ...
        lon_perm,lat_perm);

    LH_era5 = read_era5_cells( ...
        avg_file,'avg_slhtf', ...
        lon_raw_idx,lat_raw_idx, ...
        lon_perm,lat_perm);

    LWn_e5 = read_era5_cells( ...
        avg_file,'avg_snlwrf', ...
        lon_raw_idx,lat_raw_idx, ...
        lon_perm,lat_perm);

    SWn_e5 = read_era5_cells( ...
        avg_file,'avg_snswrf', ...
        lon_raw_idx,lat_raw_idx, ...
        lon_perm,lat_perm);

    T_all = [T_all; t_inst(:)];

    u_all = [u_all; u];
    v_all = [v_all; v];
    Ta_all = [Ta_all; Ta];
    Td_all = [Td_all; Td];
    p_all = [p_all; p];
    msl_all = [msl_all; msl];
    sic_all = [sic_all; sic];

    LWd_all = [LWd_all; LWd];
    SWd_all = [SWd_all; SWd];

    SH_era5_all = [SH_era5_all; SH_era5];
    LH_era5_all = [LH_era5_all; LH_era5];
    LWnet_era5_all = [LWnet_era5_all; LWn_e5];
    SWnet_era5_all = [SWnet_era5_all; SWn_e5];
end


[T_all,order] = sort(T_all);

u_all = u_all(order,:);
v_all = v_all(order,:);
Ta_all = Ta_all(order,:);
Td_all = Td_all(order,:);
p_all = p_all(order,:);
