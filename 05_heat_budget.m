function area_m2 = projected_pixel_ground_area( ...
    X,Y,dx_map,dy_map,crs3413)

    ellipsoid = wgs84Ellipsoid('meter');

    [lat_x1,lon_x1] = projinv( ...
        crs3413,X-dx_map/2,Y);

    [lat_x2,lon_x2] = projinv( ...
        crs3413,X+dx_map/2,Y);

    ground_dx = distance( ...
        lat_x1,lon_x1, ...
        lat_x2,lon_x2,ellipsoid);

    [lat_y1,lon_y1] = projinv( ...
        crs3413,X,Y-dy_map/2);

    [lat_y2,lon_y2] = projinv( ...
        crs3413,X,Y+dy_map/2);

    ground_dy = distance( ...
        lat_y1,lon_y1, ...
        lat_y2,lon_y2,ellipsoid);

    area_m2 = ground_dx.*ground_dy;
end

function [Obs,A] = ...
    deduplicate_observations(Obs,A)

    date_key = dateshift(Obs.UTC,'start','day');

    unique_days = unique(date_key);
    keep = false(height(Obs),1);

    for i = 1:numel(unique_days)
        ids = find(date_key==unique_days(i));

        if numel(ids)==1
            keep(ids)=true;
            continue;
        end

        priority = zeros(numel(ids),1);

        for j = 1:numel(ids)
            s = lower(Obs.MaskSource(ids(j)));

            if contains(s,"finalmask") || ...
               s=="final_mask"
                priority(j)=4;
            elseif contains(s,"polynya")
                priority(j)=3;
            elseif contains(s,"final_auto")
                priority(j)=2;
            else
                priority(j)=1;
            end
        end

        [~,best] = max(priority);
        keep(ids(best))=true;
    end

    Obs = Obs(keep,:);
    A = A(keep,:);
end

function [EventTable,EventNodes] = ...
    detect_events_from_observations(Obs,A,cfg)

    area_km2 = sum(A,2)/1e6;
    positive = area_km2> ...
        cfg.minimum_positive_area_km2;

    EventID = zeros(0,1);
    EventName = strings(0,1);
    StartUTC = NaT(0,1,'TimeZone','UTC');
    EndUTC = NaT(0,1,'TimeZone','UTC');
    FirstPositiveUTC = NaT(0,1,'TimeZone','UTC');
    LastPositiveUTC = NaT(0,1,'TimeZone','UTC');
    NPositiveSAR = zeros(0,1);
    BoundaryMethod = strings(0,1);

    EventNodes = struct( ...
        'EventID',{}, ...
        'NodeUTC',{}, ...
        'NodeAreaByCell_m2',{});

    event_count = 0;
    i = 1;

    while i<=height(Obs)
        if ~positive(i)
            i = i+1;
            continue;
        end

        event_count = event_count+1;
        first_id = i;
        last_id = i;

        j = i+1;

        while j<=height(Obs)
            if ~positive(j)
                break;
            end

            gap_hours = hours( ...
                Obs.UTC(j)-Obs.UTC(j-1));

            if gap_hours> ...
                    cfg.maximum_continuous_gap_hours
                break;
            end

            last_id = j;
            j = j+1;
        end

        % Conservative temporal boundaries: do not extend an event
        % before the first positive SAR observation.
        node_time = Obs.UTC(first_id);
        node_area = A(first_id,:);

        start_boundary = Obs.UTC(first_id);
        boundary_tokens = "positive_observations_only";


        if last_id>first_id
            node_time = [ ...
                node_time; ...
                Obs.UTC(first_id+1:last_id)];

            node_area = [ ...
                node_area; ...
                A(first_id+1:last_id,:)];
        end

        % Do not extend an event after the last positive SAR observation.
        end_boundary = Obs.UTC(last_id);

        EventID(end+1,1) = event_count; %#ok<AGROW>
        EventName(end+1,1) = ...
            "Event "+string(event_count); %#ok<AGROW>

        StartUTC(end+1,1) = start_boundary; %#ok<AGROW>
        EndUTC(end+1,1) = end_boundary; %#ok<AGROW>

        FirstPositiveUTC(end+1,1) = ...
            Obs.UTC(first_id); %#ok<AGROW>

        LastPositiveUTC(end+1,1) = ...
            Obs.UTC(last_id); %#ok<AGROW>

        NPositiveSAR(end+1,1) = ...
            last_id-first_id+1; %#ok<AGROW>

        BoundaryMethod(end+1,1) = ...
            boundary_tokens; %#ok<AGROW>

        EventNodes(event_count).EventID = event_count;
        EventNodes(event_count).NodeUTC = node_time;
        EventNodes(event_count).NodeAreaByCell_m2 = ...
            node_area;

        i = max(j,last_id+1);
    end

    EventTable = table( ...
        EventID,EventName,StartUTC,EndUTC, ...
        FirstPositiveUTC,LastPositiveUTC, ...
        NPositiveSAR,BoundaryMethod);
end

function EventTable = read_manual_events(csv_file)
    E = readtable(csv_file,'TextType','string');

    required = [ ...
        "EventID","StartUTC","EndUTC"];

    if ~all(ismember( ...
            required,E.Properties.VariableNames))
        error('Manual event CSV is missing required fields.');
    end

    E.StartUTC = ensure_utc_datetime(E.StartUTC);
    E.EndUTC = ensure_utc_datetime(E.EndUTC);

    if ismember('Include',E.Properties.VariableNames)
        E = E(logical(E.Include),:);
    end

    if ~ismember('EventName',E.Properties.VariableNames)
        E.EventName = ...
            "Event "+string(E.EventID);
    end

    EventTable = E(:,intersect( ...
        {'EventID','EventName','StartUTC','EndUTC'}, ...
        E.Properties.VariableNames,'stable'));
end

function EventNodes = build_nodes_from_manual_events( ...
    EventTable,Obs,A)

    EventNodes = struct( ...
        'EventID',{}, ...
        'NodeUTC',{}, ...
        'NodeAreaByCell_m2',{});

    for e = 1:height(EventTable)
        use = ...
            Obs.UTC>=EventTable.StartUTC(e) & ...
            Obs.UTC<=EventTable.EndUTC(e) & ...
            sum(A,2)>0;

        node_time = Obs.UTC(use);
        node_area = A(use,:);

        % Manual event windows select observations only. Conservative
        % integration never inserts zero-area boundary nodes and never
        % extrapolates beyond the first or last positive observation.

        EventNodes(e).EventID = ...
            EventTable.EventID(e);

        EventNodes(e).NodeUTC = node_time;
        EventNodes(e).NodeAreaByCell_m2 = node_area;
    end
end

function D = read_era5_cells( ...
    ncfile,varname,lon_raw_idx,lat_raw_idx, ...
    lon_perm,lat_perm)

    t = ncread(ncfile,'valid_time');

    lon_start = min(lon_raw_idx);
    lon_end = max(lon_raw_idx);

    lat_start = min(lat_raw_idx);
    lat_end = max(lat_raw_idx);

    start = [lon_start lat_start 1];

    count = [ ...
        lon_end-lon_start+1, ...
        lat_end-lat_start+1, ...
        numel(t)];

    raw = double(ncread( ...
        ncfile,varname,start,count));

    lon_pos = lon_raw_idx-lon_start+1;
    lat_pos = lat_raw_idx-lat_start+1;

    raw = raw(lon_pos,lat_pos,:);

    raw = raw(lon_perm,lat_perm,:);

    % [lon lat time] -> [time lat lon] -> [time cell]
    raw = permute(raw,[3 2 1]);
    D = reshape(raw,size(raw,1),[]);
end

function [Ac,Al,EventIDHour] = ...
    interpolate_event_area_cells_scenarios( ...
    time_mid,EventTable,EventNodes,nCell,max_gap_hours)

    nT = numel(time_mid);

    Ac = zeros(nT,nCell);
    Al = zeros(nT,nCell);
    EventIDHour = zeros(nT,1);

    for e = 1:height(EventTable)
        id_event = EventTable.EventID(e);

        node_id = find( ...
            [EventNodes.EventID]==id_event,1);

        if isempty(node_id)
            continue;
        end

        tn = EventNodes(node_id).NodeUTC;
        An = EventNodes(node_id).NodeAreaByCell_m2;

        [tn,order] = sort(tn);
        An = An(order,:);

        [tn,ia] = unique(tn,'stable');
        An = An(ia,:);

        if numel(tn)<2
            continue;
        end

        for k = 1:numel(tn)-1
            t1 = tn(k);
            t2 = tn(k+1);

            if t2<=t1
                continue;
            end

            if hours(t2-t1)>max_gap_hours
                continue;
            end

            % Retain only complete ERA5 hourly intervals contained between
            % the two SAR acquisition times; partial boundary hours are
            % excluded from the conservative integral.
            hour_start = time_mid-minutes(30);
            hour_end = time_mid+minutes(30);
            use = hour_start>=t1 & hour_end<=t2;

            if ~any(use)
                continue;
            end

            A1 = An(k,:);
            A2 = An(k+1,:);

            % Primary scenario: first-order linear interpolation of the
            % expert-confirmed cell area between the two SAR acquisitions.
            f = seconds(time_mid(use)-t1)/seconds(t2-t1);
            Ac(use,:) = (1-f).*A1 + f.*A2;

            % Sensitivity scenario: retain the smaller bracketing area in
            % each ERA5 cell. This is not a physical model or strict lower
            % bound; it tests sensitivity to a reduced persistence area.
            Aminimum = min(A1,A2);
            Al(use,:) = repmat(Aminimum,sum(use),1);


            EventIDHour(use) = id_event;
        end

        % A single positive observation has no constrained duration and
        % therefore contributes no cumulative heat loss or potential ice production.
    end
end

function y = safe_divide(a,b)
    y = a./b;
    y(~isfinite(y) | b<=0) = NaN;
end

function e = buck_es_water(Tc)
    e = 611.21.*exp( ...
        (18.678-Tc./234.5).* ...
        (Tc./(257.14+Tc)));
end
