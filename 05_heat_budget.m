Acq = readtable( ...
    cfg.acquisition_csv,'TextType','string');

if ~ismember('Name',Acq.Properties.VariableNames)
    error('Acquisition manifest is missing the Name column.');
end

Acq.SourceName = string(Acq.Name);

if ismember('MidUTC',Acq.Properties.VariableNames)
    Acq.MidUTC = ensure_utc_datetime(Acq.MidUTC);
else
    Acq.MidUTC = NaT(height(Acq),1,'TimeZone','UTC');

    for i = 1:height(Acq)
        Acq.MidUTC(i) = ...
            parse_sentinel1_midtime(Acq.SourceName(i));
    end
end

Acq.DateToken = strings(height(Acq),1);
Acq.SourceFile = strings(height(Acq),1);

for i = 1:height(Acq)
    Acq.DateToken(i) = extract_date_token( ...
        Acq.SourceName(i));

    if isfile(Acq.SourceName(i))
        Acq.SourceFile(i) = Acq.SourceName(i);
    else
        Acq.SourceFile(i) = string(fullfile( ...
            cfg.processed_dir, ...
            Acq.SourceName(i)));
    end
end

