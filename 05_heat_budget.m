        "polynya_mask", ...
        "final_auto_mask"];

    for i = 1:numel(preferred)
        if ismember(preferred(i),names)
            T = load(mask_file,char(preferred(i)));
            mask = logical(T.(preferred(i)));
            source = preferred(i);
            threshold = cfg.rf_threshold;
            return;
        end
    end

    if ismember("map_classes",names)
        T = load(mask_file, ...
            'map_classes','th_list');

        C = T.map_classes;

        if isfield(T,'th_list')
            th_list = double(T.th_list(:));
        else
            th_list = cfg.rf_threshold;
        end

        [~,ith] = min(abs( ...
            th_list-cfg.rf_threshold));

        C = move_threshold_dimension_last( ...
            C,numel(th_list));

        mask = logical(C(:,:,ith));

        source = "map_classes";
        threshold = th_list(ith);
        return;
    end

    if cfg.allow_probability_fallback && ...
            ismember("map_prob",names)

        T = load(mask_file,'map_prob');

        mask = T.map_prob>=cfg.rf_threshold;
        source = "map_prob_fallback";
        threshold = cfg.rf_threshold;
        return;
    end

    error('No usable final-mask variable was found in file: %s', ...
        mask_file);
end

function C = move_threshold_dimension_last(C,nThreshold)
    s = size(C);

    if ndims(C)==2
        C = reshape(C,size(C,1),size(C,2),1);
        return;
    end

    threshold_dim = find(s==nThreshold,1,'last');

    if isempty(threshold_dim)
        error('Could not determine the threshold dimension of map_classes.');
    end

    remaining = setdiff(1:ndims(C),threshold_dim,'stable');
    C = permute(C,[remaining threshold_dim]);

    if ndims(C)>3
        error('map_classes has more dimensions than expected.');
    end
end

