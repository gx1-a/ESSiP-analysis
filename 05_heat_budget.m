        G = load(mask_file,'xv','yv');
        grid_xv = double(G.xv(:)');
        grid_yv = double(G.yv(:));
    end

    if ismember("source_name",names)
        T = load(mask_file,'source_name');
        result_source_name = string(T.source_name);
    end

    if ismember("acquisition_mid_utc",names)
        T = load(mask_file,'acquisition_mid_utc');
