    string(T_all(1)),string(T_all(end)), ...
    numel(T_all));

%% ========================================================================

% ========================================================================


time_end = T_all(2:end);
time_mid = time_end-minutes(30);

u10 = 0.5*(u_all(1:end-1,:)+u_all(2:end,:));
v10 = 0.5*(v_all(1:end-1,:)+v_all(2:end,:));

t2m = 0.5*(Ta_all(1:end-1,:)+Ta_all(2:end,:));
d2m = 0.5*(Td_all(1:end-1,:)+Td_all(2:end,:));

sp = 0.5*(p_all(1:end-1,:)+p_all(2:end,:));
msl = 0.5*(msl_all(1:end-1,:)+msl_all(2:end,:));
siconc = 0.5*(sic_all(1:end-1,:)+sic_all(2:end,:));

LW_down = LWd_all(2:end,:);
SW_down = SWd_all(2:end,:);

era5_SH = SH_era5_all(2:end,:);
era5_LH = LH_era5_all(2:end,:);
era5_LWnet = LWnet_era5_all(2:end,:);
era5_SWnet = SWnet_era5_all(2:end,:);

sigma = 5.670374419e-8;
R_d = 287.05;
C_p = 1004.67;

T_water = cfg.T_water_C+273.15;
L_v = 2.501e6-2370*cfg.T_water_C;

wind_speed = hypot(u10,v10);

e_air = buck_es_water(d2m-273.15);
q_air = 0.622.*e_air./(sp-0.378.*e_air);

e_surface = 0.98* ...
    buck_es_water(cfg.T_water_C);

q_surface = 0.622.*e_surface./ ...
    (sp-0.378.*e_surface);

T_virtual = t2m.*(1+0.61.*q_air);
rho_air = sp./(R_d.*T_virtual);

Q_H = rho_air.*C_p.*cfg.C_H.* ...
    wind_speed.*(T_water-t2m);

Q_E = rho_air.*L_v.*cfg.C_E.* ...
    wind_speed.*(q_surface-q_air);

Q_LW = cfg.epsilon_w.* ...
    (sigma*T_water^4-LW_down);

Q_SW = (1-cfg.alpha_w).*SW_down;


Q_net_raw = Q_H+Q_E+Q_LW-Q_SW;


Q_freeze = max(Q_net_raw,0);

Q_era5_loss = -( ...
    era5_SH+era5_LH+ ...
    era5_LWnet+era5_SWnet);

%% ========================================================================

% ========================================================================

[A_central,A_lower,HourlyEventID] = interpolate_event_area_cells_scenarios( ...
    time_mid,EventTable,EventNodes,nCell, ...
    cfg.maximum_continuous_gap_hours);

A_total_central = sum(A_central,2);
A_total_lower = sum(A_lower,2);

active_hour = A_total_central>0;

fprintf('\nEvent-constrained hours: %d h\n', ...
    sum(active_hour));

%% ========================================================================

% ========================================================================


P_H = sum(Q_H.*A_central,2,'omitnan');
P_E = sum(Q_E.*A_central,2,'omitnan');
