cfg.era5_root = era5_root;

cfg.processed_dir = ...
    fullfile(project_root,'processed');

cfg.ridge_file = fullfile(cfg.processed_dir,'ridge', ...
    'edge_consensus_footprint','ridge_edge_consensus_final.mat');

cfg.result_dir = ...
    fullfile(project_root,'scene_eval_RF_clean');

cfg.manual_mask_dir = fullfile(cfg.result_dir,'manual_qc');
cfg.require_manual_masks = true;

cfg.acquisition_csv = fullfile( ...
    cfg.processed_dir, ...
    'Sentinel1_acquisition_times_20251122_20260430.csv');

cfg.output_dir = fullfile( ...
    cfg.processed_dir, ...
    'SAR_constrained_heat_budget_ERA5_cells_expertQC');

if ~exist(cfg.output_dir,'dir')
    mkdir(cfg.output_dir);
end


cfg.rf_threshold = 0.60;




cfg.allow_probability_fallback = false;


cfg.minimum_positive_area_km2 = 0;  % positive means area > 0 km^2



cfg.era5_lon_bounds = [160.75 162.25];
cfg.era5_lat_bounds = [72.25 73.05];



cfg.maximum_continuous_gap_hours = 48;
% This permits interpolation over at most two days. Longer gaps are split
% because continuity of the opening is not constrained by SAR observations.


% Event boundaries are the first and last positive expert-confirmed SAR
% observations; zero-positive midpoints are not used.




cfg.event_mode = "auto";


% EventID, EventName, StartUTC, EndUTC, Include
cfg.manual_event_csv = fullfile( ...
    cfg.output_dir, ...
    'Polynya_Event_Definitions_Manual.csv');


cfg.T_water_C = -1.8;
cfg.alpha_w = 0.07;
cfg.epsilon_w = 0.97;
cfg.C_H = 1.75e-3;
cfg.C_E = 1.75e-3;

cfg.rho_ice = 920;
cfg.L_f = 3.34e5;

% Salt-rejection conversion used in the manuscript.
cfg.water_salinity_g_kg = 30;
cfg.salt_rejection_fraction = 0.69;
cfg.water_salinity_sensitivity_g_kg = [28 33];
cfg.salt_rejection_fraction_sensitivity = [0.69 0.80];


cfg.test_mode = false;
cfg.test_max_scenes = 12;

%% ========================================================================

% ========================================================================

inst_files = dir(fullfile( ...
    cfg.era5_root,'**', ...
    'data_stream-oper_stepType-instant.nc'));

if isempty(inst_files)
    error('No ERA5 instant files were found under %s.', ...
        cfg.era5_root);
end


[~,file_order] = sort(string({inst_files.folder}));
inst_files = inst_files(file_order);

first_inst = fullfile( ...
    inst_files(1).folder,inst_files(1).name);

lon_raw = double(ncread(first_inst,'longitude'));
lat_raw = double(ncread(first_inst,'latitude'));

lon_raw_360 = mod(lon_raw,360);
lon_bounds_360 = mod(cfg.era5_lon_bounds,360);

if lon_bounds_360(1)>lon_bounds_360(2)
    error('This script requires ERA5 longitude bounds that do not cross 0 degrees.');
end

lon_raw_idx = find( ...
    lon_raw_360>=lon_bounds_360(1) & ...
    lon_raw_360<=lon_bounds_360(2));

lat_raw_idx = find( ...
    lat_raw>=min(cfg.era5_lat_bounds) & ...
    lat_raw<=max(cfg.era5_lat_bounds));

if isempty(lon_raw_idx) || isempty(lat_raw_idx)
    error('No ERA5 grid-cell centers fall inside the specified study region.');
end


[lon_sorted,lon_perm] = sort(lon_raw_360(lon_raw_idx));
[lat_sorted,lat_perm] = sort(lat_raw(lat_raw_idx));

nLon = numel(lon_sorted);
nLat = numel(lat_sorted);
nCell = nLon*nLat;

lon_edges = centres_to_edges(lon_sorted);
lat_edges = centres_to_edges(lat_sorted);

[CellLon_deg,CellLat_deg] = meshgrid( ...
    lon_sorted,lat_sorted);

CellID = reshape(1:nCell,nLat,nLon);
CellID = CellID(:);

ERA5CellTable = table( ...
    CellID,CellLon_deg(:),CellLat_deg(:), ...
    'VariableNames', ...
    {'CellID','Longitude_deg','Latitude_deg'});

fprintf('ERA5 cellwise domain: %d lat x %d lon = %d cells\n', ...
    nLat,nLon,nCell);
fprintf('Longitude centers: %.2f–%.2f°E; latitude centers: %.2f–%.2f°N\n', ...
    min(lon_sorted),max(lon_sorted), ...
    min(lat_sorted),max(lat_sorted));

%% ========================================================================

% ========================================================================

if ~isfile(cfg.acquisition_csv)
    error('Sentinel-1 acquisition manifest not found: %s', ...
        cfg.acquisition_csv);
