% ========================================================================

mask_catalog = build_mask_catalog( ...
    cfg.result_dir,cfg.manual_mask_dir, ...
    cfg.require_manual_masks);

if isempty(mask_catalog)
    error('No Result4 or FinalMask files were found in %s.', ...
        cfg.result_dir);
end

if cfg.test_mode
    mask_catalog = mask_catalog( ...
        1:min(cfg.test_max_scenes,height(mask_catalog)),:);

    fprintf('TEST MODE: processing only the first %d masks.\n', ...
        height(mask_catalog));
end

nObs0 = height(mask_catalog);

% Common SAR grid generated by 01. This allows the original author-reviewed
% FinalMask files to be used unchanged even when they do not store xv/yv.
ridge_X = [];
ridge_Y = [];
ridge_target_size = [];
if isfile(cfg.ridge_file)
    G = load(cfg.ridge_file,'X_master','Y_master');
    if isfield(G,'X_master') && isfield(G,'Y_master') && ...
            isequal(size(G.X_master),size(G.Y_master))
        ridge_X = double(G.X_master);
        ridge_Y = double(G.Y_master);
        ridge_target_size = size(ridge_X);
    end
end

ObsUTC = NaT(nObs0,1,'TimeZone','UTC');
ObsDateToken = strings(nObs0,1);
MaskFile = strings(nObs0,1);
SourceFile = strings(nObs0,1);
MaskSource = strings(nObs0,1);
MaskThreshold = nan(nObs0,1);
MaskPixelCount = zeros(nObs0,1);
TotalArea_m2 = zeros(nObs0,1);
AreaInsideERA5Domain_m2 = zeros(nObs0,1);
OutsideDomainFraction = nan(nObs0,1);
LoadStatus = strings(nObs0,1);

AreaByCell_m2 = zeros(nObs0,nCell);

for i = 1:nObs0
    date_token = mask_catalog.DateToken(i);
    mask_file = mask_catalog.MaskFile(i);

    fprintf('\n[%d/%d] %s\n', ...
        i,nObs0,date_token);

    ObsDateToken(i) = date_token;
    MaskFile(i) = mask_file;


    [mask,mask_source,mask_threshold, ...
        result_source_name,result_mid_utc,mask_xv,mask_yv] = ...
        load_polynya_mask(mask_file,cfg);

    if cfg.require_manual_masks && mask_source~="final_mask"
        error('Non-manual mask encountered for %s: %s', ...
            char(date_token),char(mask_source));
    end

    MaskSource(i) = mask_source;
    MaskThreshold(i) = mask_threshold;


    [source_file,obs_utc] = match_source_scene( ...
        date_token,result_source_name,result_mid_utc, ...
        Acq,cfg.processed_dir);

    SourceFile(i) = source_file;
    ObsUTC(i) = obs_utc;

    if ~isempty(mask_xv) && ~isempty(mask_yv)
        [X,Y] = meshgrid(double(mask_xv(:)'),double(mask_yv(:)));
        target_size = size(X);
    elseif ~isempty(ridge_X)
        X = ridge_X;
        Y = ridge_Y;
        target_size = ridge_target_size;
    else
        if ~isfile(source_file)
            warning(['FinalMask lacks embedded xv/yv, the rough-ice grid is ' ...
                'unavailable, and the processed SAR source file does not ' ...
                'exist; skipping: %s'],source_file);
            LoadStatus(i) = "missing_geometry";
            continue;
        end
        [target_size,X,Y] = load_source_geometry(source_file);
    end

    mask = align_mask_to_source(mask,target_size);

    positive_idx = find(mask);

    MaskPixelCount(i) = numel(positive_idx);

    if isempty(positive_idx)
        LoadStatus(i) = "zero_mask";
        fprintf('  %s: no polynya pixels passed object-level screening.\n', ...
            mask_source);
        continue;
    end

    Xp = X(positive_idx);
    Yp = Y(positive_idx);

    % EPSG:3413 -> WGS84
    crs3413 = projcrs(3413);
    [latp,lonp] = projinv(crs3413,Xp,Yp);
    lonp360 = mod(lonp,360);


    dx_map = estimate_grid_spacing_x(X,Y);
    dy_map = estimate_grid_spacing_y(X,Y);

    pixel_area_m2 = projected_pixel_ground_area( ...
        Xp,Yp,dx_map,dy_map,crs3413);

    TotalArea_m2(i) = sum(pixel_area_m2,'omitnan');

    lon_bin = discretize(lonp360,lon_edges);
    lat_bin = discretize(latp,lat_edges);

    inside = ...
        isfinite(lon_bin) & ...
        isfinite(lat_bin) & ...
        isfinite(pixel_area_m2);

    if any(inside)
        cell_id = sub2ind( ...
            [nLat nLon], ...
            lat_bin(inside), ...
            lon_bin(inside));

        area_cell = accumarray( ...
            cell_id,pixel_area_m2(inside), ...
            [nCell 1],@sum,0);

        AreaByCell_m2(i,:) = area_cell';
    end

    AreaInsideERA5Domain_m2(i) = ...
        sum(AreaByCell_m2(i,:));

    OutsideDomainFraction(i) = ...
        1-AreaInsideERA5Domain_m2(i)/ ...
        max(TotalArea_m2(i),eps);

    if OutsideDomainFraction(i)>0.01
        warning(['%.1f%% of mask area for %s lies outside the ERA5 domain; ' ...
            'expand the latitude/longitude bounds.'], ...
            date_token,100*OutsideDomainFraction(i));

        LoadStatus(i) = "partial_outside_domain";
    else
        LoadStatus(i) = "ok";
    end

    fprintf(['  source=%s; threshold=%.2f; pixels=%d; ' ...
        'total area=%.2f km2; inside domain=%.2f km2\n'], ...
        mask_source,mask_threshold, ...
        MaskPixelCount(i), ...
        TotalArea_m2(i)/1e6, ...
        AreaInsideERA5Domain_m2(i)/1e6);
end

ObservationTable = table( ...
    ObsUTC,ObsDateToken,MaskFile,SourceFile, ...
    MaskSource,MaskThreshold,MaskPixelCount, ...
    TotalArea_m2/1e6, ...
    AreaInsideERA5Domain_m2/1e6, ...
    OutsideDomainFraction,LoadStatus, ...
    'VariableNames',{ ...
    'UTC','DateToken','MaskFile','SourceFile', ...
    'MaskSource','MaskThreshold','MaskPixelCount', ...
    'TotalArea_km2','AreaInsideERA5Domain_km2', ...
    'OutsideDomainFraction','Status'});


usable_obs = ...
    ~isnat(ObservationTable.UTC) & ...
    ObservationTable.Status~="missing_source" & ...
    ObservationTable.Status~="missing_geometry";

ObservationTable = ObservationTable(usable_obs,:);
AreaByCell_m2 = AreaByCell_m2(usable_obs,:);

[ObservationTable,obs_order] = ...
    sortrows(ObservationTable,'UTC');

AreaByCell_m2 = AreaByCell_m2(obs_order,:);


[ObservationTable,AreaByCell_m2] = ...
    deduplicate_observations( ...
    ObservationTable,AreaByCell_m2);

writetable(ObservationTable,fullfile( ...
    cfg.output_dir, ...
    'SAR_Polynya_Observation_Area.csv'));


long_rows = [];

for i = 1:height(ObservationTable)
    ids = find(AreaByCell_m2(i,:)>0);

    if isempty(ids)
        continue;
    end

    Ti = table( ...
        repmat(ObservationTable.UTC(i),numel(ids),1), ...
        repmat(ObservationTable.DateToken(i),numel(ids),1), ...
        ids(:), ...
        ERA5CellTable.Longitude_deg(ids), ...
        ERA5CellTable.Latitude_deg(ids), ...
        AreaByCell_m2(i,ids)'/1e6, ...
        'VariableNames',{ ...
        'UTC','DateToken','CellID', ...
        'ERA5Longitude_deg','ERA5Latitude_deg', ...
        'Area_km2'});

    long_rows = [long_rows; Ti]; %#ok<AGROW>
end

if ~isempty(long_rows)
    writetable(long_rows,fullfile( ...
        cfg.output_dir, ...
        'SAR_Area_By_ERA5_Cell.csv'));
end

