for k = 1:numel(inst_files)
    inst_file = fullfile( ...
        inst_files(k).folder,inst_files(k).name);

    avg_file = fullfile( ...
        inst_files(k).folder, ...
        'data_stream-oper_stepType-avg.nc');

    if ~isfile(avg_file)
        error('Matching ERA5 avg file is missing: %s',avg_file);
