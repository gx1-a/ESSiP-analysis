    fprintf('\nERA5 [%d/%d] %s\n', ...
        k,numel(inst_files),inst_files(k).folder);

    t_inst = datetime( ...
        ncread(inst_file,'valid_time'), ...
        'ConvertFrom','posixtime', ...
        'TimeZone','UTC');

    t_avg = datetime( ...
        ncread(avg_file,'valid_time'), ...
