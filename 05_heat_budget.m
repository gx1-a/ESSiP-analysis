%% 05_heat_budget.m
% Purpose: Calculate the SAR-constrained surface heat budget and estimate
% potential ice production and potential salt rejection.
%
% Within a multiscene event, the reference scenario linearly interpolates
% polynya area in each ERA5 grid cell. The conservative temporal-area scenario
% retains the smaller of the two bracketing cell areas. Confirmed zero-area
% scenes and gaps longer than 48 h end an event; isolated positive scenes are
% assigned no duration, and no area is extrapolated outside event windows.
%
% SAR-observed polynya masks may include thin ice. The heat-budget results are
% therefore interpreted as potential estimates under open-water conditions.
% Inputs: expert-confirmed FinalMask files, acquisition manifest, and ERA5.
% If a FinalMask does not contain grid vectors, geometry is taken from the
% rough-ice footprint generated by 01; processed SAR geometry is only a
% backward-compatible fallback.
% MATLAB: R2022b

clear; clc; close all;


%% Repository paths
